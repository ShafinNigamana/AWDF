const express = require('express');
const router = express.Router();
const authenticate = require('../middleware/auth');

// In-memory rate limiting map: key -> timestamp
const rateLimitMap = new Map();
const RATE_LIMIT_WINDOW_MS = 60 * 1000; // 1 minute per task/user

const clearExpiredRateLimits = () => {
  const now = Date.now();
  for (const [key, timestamp] of rateLimitMap.entries()) {
    if (now - timestamp > RATE_LIMIT_WINDOW_MS) {
      rateLimitMap.delete(key);
    }
  }
};

router.post('/generate-description', authenticate, async (req, res, next) => {
  const { title, taskId } = req.body || {};

  // 1. Input Validation
  if (typeof title !== 'string' || !title.trim()) {
    return res.status(400).json({
      error: 'Validation failed',
      message: 'Task title is required to generate a description'
    });
  }

  const trimmedTitle = title.trim();
  if (trimmedTitle.length < 3 || trimmedTitle.length > 150) {
    return res.status(400).json({
      error: 'Validation failed',
      message: 'Task title must be between 3 and 150 characters'
    });
  }

  // 2. Rate Limiting Check (approx 1 request per task/user per minute)
  const rateLimitKey = taskId ? `task:${taskId}` : `user:${req.user.id}:${trimmedTitle.toLowerCase()}`;
  const lastRequestTime = rateLimitMap.get(rateLimitKey);
  const now = Date.now();

  if (lastRequestTime && now - lastRequestTime < RATE_LIMIT_WINDOW_MS) {
    const remainingSeconds = Math.ceil((RATE_LIMIT_WINDOW_MS - (now - lastRequestTime)) / 1000);
    return res.status(429).json({
      error: 'Rate limit exceeded',
      message: `Rate limit reached. Please wait ${remainingSeconds} second(s) before generating another description for this task.`,
      retryAfterSeconds: remainingSeconds
    });
  }

  // 3. API Key Check
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey || apiKey === 'your_gemini_api_key_here') {
    return res.status(503).json({
      error: 'AI service unavailable',
      message: 'GEMINI_API_KEY is not configured on the server. Core task features remain operational.'
    });
  }

  const model = process.env.GEMINI_MODEL || 'gemini-3.5-flash-lite';
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;

  try {
    const prompt = `Write a concise, actionable, 1 to 2 sentence task description for a task titled "${trimmedTitle}". Output ONLY the plain text description with no quotes, markdown formatting, or preamble.`;

    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 10000); // 10s timeout

    const apiResponse = await fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        contents: [
          {
            parts: [{ text: prompt }]
          }
        ],
        generationConfig: {
          temperature: 0.7,
          maxOutputTokens: 150
        }
      }),
      signal: controller.signal
    });

    clearTimeout(timeoutId);

    if (!apiResponse.ok) {
      const errBody = await apiResponse.json().catch(() => null);
      console.error('[AI Error] Gemini API returned status:', apiResponse.status, errBody);
      return res.status(502).json({
        error: 'AI provider error',
        message: errBody?.error?.message || 'External AI provider request failed. Core task features remain functional.'
      });
    }

    const data = await apiResponse.json();
    const rawDescription = data?.candidates?.[0]?.content?.parts?.[0]?.text?.trim();

    if (!rawDescription) {
      return res.status(502).json({
        error: 'AI provider error',
        message: 'The AI provider returned an empty response. Please try again or enter the description manually.'
      });
    }

    // Record rate limit timestamp
    rateLimitMap.set(rateLimitKey, now);
    clearExpiredRateLimits();

    return res.status(200).json({
      description: rawDescription,
      model,
      disclaimer: 'This description was generated by AI. Please review and verify accuracy before saving.'
    });
  } catch (error) {
    if (error.name === 'AbortError') {
      return res.status(504).json({
        error: 'Gateway timeout',
        message: 'The AI provider request timed out. Core task features remain functional.'
      });
    }

    console.error('[AI Error] Unexpected error:', error.message);
    return res.status(500).json({
      error: 'AI generation error',
      message: 'Failed to process AI description request: ' + error.message
    });
  }
});

// Helper for resetting rate limits during automated testing
router._resetRateLimits = () => rateLimitMap.clear();

module.exports = router;
